tours = ["melbourne", "adelaide", "sydney", "perth", "brisbane"]

print("\nOriginal list: ")
print(tours)

print("\nSorted list: ")
print(sorted(tours))

print("\nOriginal list: ")
print(tours)

print("\nReversed list: ")
tours.reverse()
print(tours)

print("\nReversed list: ")
tours.reverse()
print(tours)

print("\nSorted list: ")
tours.sort()
print(tours)

print("\nSorted list in reverse order: ")
tours.sort(reverse=True)
print(tours)